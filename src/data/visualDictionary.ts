/**
 * Intelligent helper to extract verified real photograph for any entry
 */
export function getVerifiedVisualImage(entry: { en?: string; hi?: string; cat?: string }): string | null {
  if (!entry) return null;

  // 1. Check English text tokens
  if (entry.en) {
    const cleanEn = entry.en.toLowerCase().replace(/[^a-z\s]/g, ' ');
    const tokens = cleanEn.split(/\s+/);
    for (const token of tokens) {
      if (token && VERIFIED_IMAGE_MAP[token]) {
        return VERIFIED_IMAGE_MAP[token];
      }
    }
  }

  // 2. Check Hindi text keywords
  if (entry.hi) {
    for (const [hiWord, enKey] of Object.entries(HINDI_KEYWORD_MAP)) {
      if (entry.hi.includes(hiWord)) {
        if (VERIFIED_IMAGE_MAP[enKey]) {
          return VERIFIED_IMAGE_MAP[enKey];
        }
      }
    }
  }

  // 3. Check Category fallback
  if (entry.cat) {
    const catLower = entry.cat.toLowerCase();
    if (catLower.includes('bird')) return VERIFIED_IMAGE_MAP['pigeon'];
    if (catLower.includes('animal')) return VERIFIED_IMAGE_MAP['cow'];
    if (catLower.includes('fruit')) return VERIFIED_IMAGE_MAP['mango'];
    if (catLower.includes('vegetable')) return VERIFIED_IMAGE_MAP['potato'];
    if (catLower.includes('classroom') || catLower.includes('school')) return VERIFIED_IMAGE_MAP['book'];
  }

  return null;
}
